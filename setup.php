    <?php if ($message !== ''): ?>
        <div class="alert ok"><?= htmlspecialchars($message, ENT_QUOTES, 'UTF-8') ?></div>
        <form method="post" action="setup.php?key=<?= $key ?>">
            <input type="hidden" name="action" value="delete_setup">
            <button class="danger" type="submit">Delete setup.php now</button>
