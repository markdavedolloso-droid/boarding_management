<?php
/**
 * One-time InfinityFree setup helper.
 *
 * Open this file in the browser with the key below, enter the MySQL details
 * from the InfinityFree Client Area, and it will create db_config.php.
 *
 * DELETE THIS FILE from the server after the site works.
 */

const SETUP_KEY = '02fd4676a6a5ca5e12787e1a7cf48ad4';

if (!hash_equals(SETUP_KEY, (string) ($_GET['key'] ?? ''))) {
    http_response_code(403);
    exit('Forbidden. Open this page with the setup key.');
}

$message = '';
$error = '';
$host = trim((string) ($_POST['host'] ?? ''));
$dbname = trim((string) ($_POST['dbname'] ?? ''));
$username = trim((string) ($_POST['username'] ?? ''));
$password = (string) ($_POST['password'] ?? '');
$doImport = isset($_POST['import']);

if (($_POST['action'] ?? '') === 'delete_setup') {
    if (@unlink(__FILE__)) {
        exit('<!doctype html><meta charset="utf-8"><p style="font-family:system-ui;padding:2rem">setup.php has been deleted. You can close this page.</p>');
    }
    $error = 'Could not delete setup.php automatically. Delete it with the File Manager.';
}

if ($_SERVER['REQUEST_METHOD'] === 'POST' && ($_POST['action'] ?? '') === 'save') {
    if ($host === '' || $dbname === '' || $username === '' || $password === '') {
        $error = 'Please fill in all four fields.';
    } elseif (!preg_match('/^[A-Za-z0-9._-]+$/', $host)) {
        $error = 'The MySQL hostname contains invalid characters.';
    } elseif (!preg_match('/^[A-Za-z0-9_-]+$/', $dbname) || !preg_match('/^[A-Za-z0-9_-]+$/', $username)) {
        $error = 'The database name and username contain invalid characters.';
    } else {
        try {
            $pdo = new PDO(
                "mysql:host={$host};dbname={$dbname};charset=utf8mb4",
                $username,
                $password,
                [
                    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                    PDO::ATTR_TIMEOUT => 15,
                ]
            );

            $tables = $pdo->query('SHOW TABLES')->fetchAll(PDO::FETCH_COLUMN);
            $imported = false;
            $sqlFile = __DIR__ . '/boarding_house_db.sql';

            if ($doImport && count($tables) === 0) {
                if (!is_file($sqlFile)) {
                    throw new RuntimeException(
                        'The database is empty, but boarding_house_db.sql was not found. ' .
                        'Upload the SQL file or import it through phpMyAdmin.'
                    );
                }
                if (!class_exists('mysqli')) {
                    throw new RuntimeException(
                        'The mysqli extension is unavailable. Please import boarding_house_db.sql through phpMyAdmin.'
                    );
                }

                $sql = file_get_contents($sqlFile);
                $mysqli = @new mysqli($host, $username, $password, $dbname);
                if ($mysqli->connect_errno) {
                    throw new RuntimeException('Import connection failed: ' . $mysqli->connect_error);
                }
                if (!$mysqli->multi_query($sql)) {
                    throw new RuntimeException('Import failed: ' . $mysqli->error);
                }
                do {
                    if ($result = $mysqli->store_result()) {
                        $result->free();
                    }
                } while ($mysqli->more_results() && $mysqli->next_result());
                if ($mysqli->errno) {
                    throw new RuntimeException('Import failed: ' . $mysqli->error);
                }
                $mysqli->close();
                $imported = true;
                $tables = $pdo->query('SHOW TABLES')->fetchAll(PDO::FETCH_COLUMN);
            }

            // The application expects this table to exist before it runs its migrations.
            if (!in_array('tenants', $tables, true)) {
                $pdo->exec(
                    "CREATE TABLE IF NOT EXISTS tenants (
                        tenant_id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
                        user_id INT UNSIGNED NULL,
                        first_name VARCHAR(50) NOT NULL,
                        last_name VARCHAR(50) NOT NULL,
                        gender ENUM('Male', 'Female', 'Other') NOT NULL,
                        contact_number VARCHAR(20) NOT NULL,
                        address VARCHAR(150) NOT NULL,
                        date_registered DATE NOT NULL DEFAULT curdate(),
                        owner_id INT UNSIGNED NULL,
                        UNIQUE KEY uq_tenants_user_id (user_id)
                    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci"
                );
            }

            $config = "<?php\n"
                . "// InfinityFree database credentials. Generated by setup.php.\n"
                . "// You can delete setup.php after installation.\n\n"
                . '$servername = ' . var_export($host, true) . ";\n"
                . '$username = ' . var_export($username, true) . ";\n"
                . '$password = ' . var_export($password, true) . ";\n"
                . '$dbname = ' . var_export($dbname, true) . ";\n";

            if (file_put_contents(__DIR__ . '/db_config.php', $config, LOCK_EX) === false) {
                throw new RuntimeException(
                    'The connection works, but db_config.php could not be written. ' .
                    'Check the folder permissions or create the file manually.'
                );
            }

            $message = 'Database connected and db_config.php was created.'
                . ($imported ? ' The SQL dump was imported.' : ' Existing tables were kept.')
                . ' Now open the site and log in. After that, delete setup.php and boarding_house_db.sql.';

            $connectionSource = is_file(__DIR__ . '/connection.php')
                ? (string) file_get_contents(__DIR__ . '/connection.php')
                : '';
            if (strpos($connectionSource, 'db_config.php') === false) {
                $message .= ' IMPORTANT: the connection.php on the server is the old version. Upload the new connection.php too.';
            }
        } catch (Throwable $e) {
            $error = $e->getMessage();
        }
    }
}

$key = htmlspecialchars(SETUP_KEY, ENT_QUOTES, 'UTF-8');
